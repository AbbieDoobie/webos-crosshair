"""Generate the native service's settings table from crosshair/shared/config.js.

Usage: python scripts/gen_schema.py <output.h>

config.js stays the one place that defines the settings. This reads its DEFAULTS, NUMBERS,
and SHAPES through Node and writes them as C tables, so the native service validates
exactly like the settings panel does. Field types come from the defaults: a boolean is a
switch, `shape` is a shape name, a string starting with # is a color, and anything in
NUMBERS is a clamped number.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG_JS = ROOT / "crosshair" / "shared" / "config.js"

DUMP = ("const c = require(process.argv[1]);"
        "process.stdout.write(JSON.stringify({d: c.DEFAULTS, n: c.NUMBERS, s: c.SHAPES}));")


def c_str(s: str) -> str:
    return json.dumps(s)    #A JSON string of plain ASCII is a valid C string literal


def c_num(v) -> str:
    return repr(float(v))


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = Path(sys.argv[1])
    raw = subprocess.run(["node", "-e", DUMP, str(CONFIG_JS)],
                         check=True, capture_output=True, text=True).stdout
    data = json.loads(raw)
    defaults, numbers, shapes = data["d"], data["n"], data["s"]

    fields = []
    for key, value in defaults.items():
        if isinstance(value, bool):
            fields.append(f"    {{ {c_str(key)}, F_BOOL, {int(value)}, 0, 0, 0, 0, \"\" }},")
        elif key == "shape":
            fields.append(f"    {{ {c_str(key)}, F_SHAPE, 0, 0, 0, 0, 0, {c_str(value)} }},")
        elif isinstance(value, str) and value.startswith("#"):
            fields.append(f"    {{ {c_str(key)}, F_COLOR, 0, 0, 0, 0, 0, {c_str(value)} }},")
        elif key in numbers:
            n = numbers[key]
            fields.append(f"    {{ {c_str(key)}, F_NUM, 0, {c_num(value)}, {c_num(n['min'])}, "
                          f"{c_num(n['max'])}, {c_num(n['step'])}, \"\" }},")
        else:
            sys.exit(f"gen_schema: can't tell the type of setting '{key}'")

    lines = [
        "/* Generated by scripts/gen_schema.py from crosshair/shared/config.js. Do not edit. */",
        "#ifndef CROSSHAIR_CONFIG_SCHEMA_H",
        "#define CROSSHAIR_CONFIG_SCHEMA_H",
        "",
        "static const char *const SHAPES[] = {",
        *[f"    {c_str(s)}," for s in shapes],
        "};",
        f"#define SHAPE_COUNT {len(shapes)}",
        "",
        "static const field_t FIELDS[] = {",
        *fields,
        "};",
        f"#define FIELD_COUNT {len(fields)}",
        "",
        "#endif",
        "",
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
